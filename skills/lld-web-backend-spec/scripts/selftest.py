"""Self-check for trace_check.py and md_to_html.py. Run: python3 selftest.py"""
import os, sys, tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import md_to_html, trace_check

DOC = """# LLD – Test

| ID | רכיב | מקור התוכן |
|---|---|---|
| UI-01 | כותרת | `CMS-01` כותרת, נוסח: `BQ-01` נוסח |
| | **רמה 1** | |

#### SC-01 – חישוב
| היבט | פירוט |
|---|---|
| מקורות | `CMS-01` עד `CMS-03`, `UI-01` |

- **Request:**
  ```json
  { "a": "<b>" }
  ```

- `BQ-01` נוסח: שאלה פתוחה
- `BQ-02` ישן: נסגר – ההחלטה ב-`UI-01`
- `AS-01` יתום: אף אחד לא מפנה אליה

| ID | שם שדה |
|---|---|
| CMS-01 | כותרת |
| CMS-02 | בטווח |
| CMS-03 | סוף טווח |
"""

undefined, duplicates, unused, gaps = trace_check.check(DOC + '\nראו `TQ-09`.\n')
assert undefined == ['TQ-09'], undefined
assert duplicates == [], duplicates
assert unused == ['AS-01', 'SC-01'], unused  # range covers CMS-02; closed BQ-02 is exempt
assert gaps == [], gaps

extra = '\n- `AS-02` מפנה לעצמו: ראו `AS-02`\n| CMS-01 | כפול |\n- `BQ-04` פער\n'
_, duplicates, unused, gaps = trace_check.check(DOC + extra)
assert gaps == ['BQ-03'], gaps
assert duplicates == ['CMS-01'], duplicates
assert 'AS-02' in unused, unused  # a mention on its own definition line is not a reference

page = md_to_html.render(DOC)
assert '<tr id="UI-01">' in page and '<li id="BQ-01">' in page and '<h4 id="SC-01">' in page
assert '<a class="ref" href="#CMS-01"><code>CMS-01</code></a>' in page
assert '<tr class="group"><td colspan="3"><strong>רמה 1</strong></td></tr>' in page
assert '<pre><code>{ &quot;a&quot;: &quot;&lt;b&gt;&quot; }</code></pre>' in page  # fenced block escaped, de-indented

with tempfile.TemporaryDirectory() as d:
    src = os.path.join(d, 'lld_test.md')
    open(src, 'w', encoding='utf-8').write(DOC)
    sys.argv = ['md_to_html.py', src]
    md_to_html.main()
    html = open(os.path.join(d, 'lld_test.html'), encoding='utf-8').read()
    assert 'dir="rtl"' in html and 'do not edit this file' in html

print('selftest OK')
